// Helper: Get all reservoirs for a given city or all Indian cities
export function getReservoirsForCity(cityId: string): ReservoirTelemetry[] {
  const normalized = cityId.toLowerCase();
  if (RESERVOIRS_DATABASE[normalized]) {
    return RESERVOIRS_DATABASE[normalized];
  }
  return RESERVOIRS_DATABASE['chennai'];
}

export function getAllReservoirs(): ReservoirTelemetry[] {
  return Object.values(RESERVOIRS_DATABASE).flat();
}

export function getCriticalReservoirAlerts(): ReservoirTelemetry[] {
  return getAllReservoirs().filter(r => r.capacityPct >= 90 || r.status === 'CRITICAL_FULL' || r.status === 'OVERFLOWING' || r.status === 'DISCHARGING');
}
